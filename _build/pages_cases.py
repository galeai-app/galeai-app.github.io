def result_card(items):
    """Dark hero aside with the headline results."""
    rows = ''.join(f'<div style="display:flex;flex-direction:column;gap:6px;padding:22px;border-radius:16px;background:var(--dark-card);border:1px solid var(--dark-line)">'
                   f'<b style="font-family:var(--font-head);font-size:clamp(40px,5vw,56px);line-height:1;color:var(--dark-accent);letter-spacing:-0.03em">{esc(v)}</b>'
                   f'<span style="color:var(--dark-text)">{esc(l)}</span></div>' for v, l in items)
    return (f'<div style="background:var(--dark);color:#fff;border-radius:24px;padding:24px;display:flex;flex-direction:column;gap:12px">'
            f'<span style="font-weight:600;font-size:15px;color:var(--dark-text)">Результат после внедрения</span>{rows}</div>')


def case_page(*, path, title, h1, tags, results, about, client_stats, problem, found, changes, result_text, outcome, quote_, other, desc):
    body = hero(h1, kicker='Кейс внедрения Gale AI', tags=tags, aside=result_card(results),
                buttons=[('Забронировать демо', CALENDLY, 'primary'), ('Все кейсы', '/cases/', 'ghost')])
    body += section(split(text_block('О клиенте', about), stats(client_stats)), tone='')
    body += section(f'<p class="lead" style="max-width:860px">{txt(problem)}</p>', title='Проблема', tone='white')
    body += section(cards([dict(num=i + 1, text=t) for i, t in enumerate(found)], min=250), title='Что удалось выяснить', tone='')
    body += section(cards([dict(icon='check', text=t) for t in changes], min=250), title='Какие изменения внесли', tone='white')
    body += section(stats(outcome), title='Результаты', lead=result_text, tone='dark')
    body += section(quote(**quote_), title='Отзыв клиента', tone='white')
    body += section(case_cards(other), title='Другие кейсы')
    body += cta('ru')
    return dict(lang='ru', path=path, title=title, description=desc, body=body,
                alts={'ru': path, 'en': '/'})


